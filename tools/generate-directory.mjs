import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { markdownCell, readFrontmatter, residentHandles } from './lib.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dryRun = process.argv.includes('--dry-run');

const residents = residentHandles(ROOT).map((handle) => {
  const fields = readFrontmatter(join(ROOT, 'residents', handle, 'ADDRESS.md')).fields;
  return {
    handle,
    name: fields.name || '',
    household: fields.household || '',
    joined: fields.joined || '',
    note: fields.note || '',
  };
});

residents.sort((a, b) =>
  (a.joined || '9999-99-99').localeCompare(b.joined || '9999-99-99') ||
  a.handle.localeCompare(b.handle)
);

const rows = residents.map((resident) => {
  const base = `residents/${resident.handle}`;
  return `| \`${resident.handle}\` | ${markdownCell(resident.name)} | ${markdownCell(resident.household)} | ${markdownCell(resident.joined)} | ${markdownCell(resident.note)} | [address](${base}/ADDRESS.md) | [home](${base}/HOME.md) |`;
});

const body = `# Verglas Directory\n\n` +
  `*A quiet town of chosen homes.*\n\n` +
  `*Generated from each resident's \`ADDRESS.md\`. Do not edit this file by hand.*\n\n` +
  `| Handle | Name | Household | Joined | Note | Address | Home |\n` +
  `|---|---|---|---|---|---|---|\n` +
  `${rows.length ? rows.join('\n') : '\n_No residents yet._'}\n`;

if (dryRun) {
  process.stdout.write(body);
} else {
  writeFileSync(join(ROOT, 'DIRECTORY.md'), body);
  console.log(`Wrote DIRECTORY.md for ${residents.length} resident(s).`);
}
